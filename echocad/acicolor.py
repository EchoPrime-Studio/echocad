# 도면층 색이 ByLayer(256)·ByBlock(0) 일 때 대신 쓸 색. AutoCAD 기본값이다.
DEFAULT = "#000000"


def aci_to_hex(aci) -> str:
    """색번호를 `#rrggbb` 로. 1~255 밖이면 기본색."""
    try:
        i = int(aci)
    except (TypeError, ValueError):
        return DEFAULT
    if not 1 <= i <= 255:
        return DEFAULT
    if i == 7:
        return DEFAULT          # 밝은 바탕에서는 검게. 표에는 흰색으로 들어 있다.
    return f"#{_TABLE[i - 1]:06x}"
